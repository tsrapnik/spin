"""Generate docs/img/timing.svg (v1: latch at peak) and timing-half.svg (backlog: latch at peak and valley).

    python3 scripts/gen_timing_svg.py docs/img
"""
import sys

OUT = sys.argv[1]
X0, TS = 100.0, 190.0
P = [X0 + i * TS for i in range(4)]          # peaks: sample instants k-1, k, k+1, k+2
V = [p + TS / 2 for p in P[:3]]              # valleys: centre of the high-side pulse
YT, YB = 50.0, 120.0                         # carrier peak / valley
VH, VL = 150.0, 180.0                        # phase voltage high / low
IM, S_ON, S_OFF = 232.0, 16 / 85.5, 16 / 104.5   # current mean, ripple slopes (px/px)
D_K2, D_K1, D_NEW, D_K1P = 0.42, 0.47, 0.70, 0.73  # d_k-2, d_k-1, d_k (step), d_k+1

STYLE = """  <style>
    .bg { fill: #ffffff; } .fg { fill: #24292f; } .mut { fill: #57606a; }
    .car { stroke: #24292f; stroke-width: 1.3; fill: none; }
    .ccr { stroke: #1a7f37; stroke-width: 2; fill: none; } .ccrt { fill: #1a7f37; }
    .sig { stroke: #24292f; stroke-width: 1.6; fill: none; }
    .cur { stroke: #cf222e; stroke-width: 1.6; fill: none; } .smp { fill: #cf222e; }
    .mk { stroke: #8c959f; stroke-dasharray: 3 3; } .mkv { stroke: #8c959f; stroke-dasharray: 1 4; }
    .isr { fill: #ddf4ff; stroke: #0969da; } .isrf { fill: none; stroke: #8c959f; stroke-dasharray: 3 2; }
    .dk { fill: #dafbe1; stroke: #1a7f37; } .dk1 { fill: #f6f8fa; stroke: #8c959f; }
    .arr { stroke: #0969da; stroke-width: 1.4; fill: none; } .ah { fill: #0969da; }
    .dl { stroke: #cf222e; stroke-width: 1.4; stroke-dasharray: 5 3; } .dlt { fill: #cf222e; }
    .obs { stroke: #9a6700; stroke-width: 1.4; fill: none; } .aho { fill: #9a6700; } .obst { fill: #9a6700; }
    @media (prefers-color-scheme: dark) {
      .bg { fill: #0d1117; } .fg { fill: #e6edf3; } .mut { fill: #8b949e; }
      .car, .sig { stroke: #e6edf3; }
      .ccr { stroke: #3fb950; } .ccrt { fill: #3fb950; }
      .cur { stroke: #ff7b72; } .smp { fill: #ff7b72; }
      .mk, .mkv { stroke: #6e7681; }
      .isr { fill: #0c2d6b; stroke: #4493f8; } .isrf { stroke: #6e7681; }
      .dk { fill: #04260f; stroke: #3fb950; } .dk1 { fill: #161b22; stroke: #6e7681; }
      .arr { stroke: #4493f8; } .ah { fill: #4493f8; }
      .dl { stroke: #ff7b72; } .dlt { fill: #ff7b72; }
      .obs { stroke: #d29922; } .aho, .obst { fill: #d29922; }
    }
  </style>"""


def f(x):
    return f"{x:.1f}".rstrip("0").rstrip(".")


def build(half):
    W, H = 720, 428
    o = []
    a = o.append
    title = ("Duty latched at peak and valley: 1.0-period delay (backlog)" if half
             else "PWM timing: sample, update and the 1.5-period duty delay")
    a(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
      'font-family="Helvetica, Arial, sans-serif" font-size="12">')
    a('  <!-- SPDX-License-Identifier: MIT -->')
    a('  <!-- Generated by scripts/gen_timing_svg.py; edit that, not this file. -->')
    a(f'  <title>{title}</title>')
    a(STYLE)
    a('  <defs>')
    a('    <marker id="a" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" '
      'orient="auto-start-reverse"><path class="ah" d="M0 0 L10 5 L0 10 z"/></marker>')
    a('    <marker id="o" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" '
      'orient="auto-start-reverse"><path class="aho" d="M0 0 L10 5 L0 10 z"/></marker>')
    a('  </defs>')
    a(f'  <rect class="bg" width="{W}" height="{H}"/>')

    # Row labels.
    for y, t in [(88, "counter, CCR"), (168, "phase voltage"), (236, "phase current"),
                 (284, "CPU"), (316, "applied duty")]:
        a(f'  <text class="mut" x="10" y="{y}" font-size="11">{t}</text>')

    # Event markers: peaks = sample + update; valleys = update too in the half scheme.
    labels = ["k−1", "k", "k+1", "k+2"]
    for p, l in zip(P, labels):
        a(f'  <line class="mk" x1="{f(p)}" y1="40" x2="{f(p)}" y2="328"/>')
        a(f'  <text class="fg" x="{f(p)}" y="34" text-anchor="middle">S/U {l}</text>')
    for v in V:
        a(f'  <line class="mkv" x1="{f(v)}" y1="{f(YB)}" x2="{f(v)}" y2="328"/>')
        if half:
            a(f'  <text class="mut" x="{f(v)}" y="133" text-anchor="middle" font-size="11">U</text>')

    # Carrier.
    pts = []
    for i in range(3):
        pts += [(P[i], YT), (V[i], YB)]
    pts.append((P[3], YT))
    a('  <path class="car" d="M' + " L".join(f"{f(x)} {f(y)}" for x, y in pts) + '"/>')

    # Duty segments (active compare value) and pulses.
    # v1: CCR changes only at peaks: [P0,P1]=old, [P1,P2]=old, [P2,P3]=new.
    # half: CCR changes at V1 (ISR k finished before it): [P0,V1]=old, [V1,P3]=new.
    if half:
        ccr = [(P[0], V[0], D_K2), (V[0], V[1], D_K1), (V[1], V[2], D_NEW), (V[2], P[3], D_K1P)]
    else:
        ccr = [(P[0], P[1], D_K2), (P[1], P[2], D_K1), (P[2], P[3], D_NEW)]
    step_x = V[1] if half else P[2]

    def duty_at(x):
        for x0, x1, d in ccr:
            if x0 <= x < x1:
                return d
        return ccr[-1][2]

    for x0, x1, d in ccr:
        y = YB - (YB - YT) * d
        a(f'  <line class="ccr" x1="{f(x0)}" y1="{f(y)}" x2="{f(x1)}" y2="{f(y)}"/>')
    a(f'  <text class="ccrt" x="{f(P[3] + 6)}" y="{f(YB - (YB - YT) * D_NEW + 4)}" font-size="11">CCR = d</text>')

    # High side on while counter < CCR: pulse centred on each valley; each edge uses the CCR
    # active at that edge.
    edges = []
    for v in V:
        on = v - TS / 2 * duty_at(v - 1e-6)
        off = v + TS / 2 * duty_at(v + 1e-6)
        edges.append((on, off))
    d = f"M{f(P[0])} {f(VL)}"
    for on, off in edges:
        d += f" H{f(on)} V{f(VH)} H{f(off)} V{f(VL)}"
    d += f" H{f(P[3])}"
    a(f'  <path class="sig" d="{d}"/>')
    a(f'  <text class="mut" x="{f(P[3] + 6)}" y="{f(VH + 4)}" font-size="11">high</text>')
    a(f'  <text class="mut" x="{f(P[3] + 6)}" y="{f(VL + 4)}" font-size="11">low</text>')

    # Current: rises while the high side is on, falls otherwise (illustrative). Before the step
    # the fall rate balances the duty, so the samples sit on the average; after it, it does not.
    def s_off(x):
        if x < step_x - 1e-6:
            d = duty_at(x)
            return S_ON * d / (1.0 - d)
        return S_OFF

    y = IM
    cpts = [(P[0], y)]
    x = P[0]
    samples = {}
    marks = sorted([e for pair in edges for e in pair] + P)
    hi = False
    for m in marks:
        if m <= x:
            if m in P:
                samples[m] = y
            continue
        y += (-S_ON if hi else s_off(x)) * (m - x)
        x = m
        cpts.append((x, y))
        if m in P:
            samples[m] = y
        if any(abs(m - e[0]) < 1e-9 for e in edges):
            hi = True
        elif any(abs(m - e[1]) < 1e-9 for e in edges):
            hi = False
    samples[P[0]] = IM
    a('  <path class="cur" d="M' + " L".join(f"{f(x)} {f(y)}" for x, y in cpts) + '"/>')
    a(f'  <line class="mk" x1="{f(P[0])}" y1="{f(IM)}" x2="{f(P[3])}" y2="{f(IM)}" opacity="0.5"/>')
    for p in P:
        a(f'  <circle class="smp" cx="{f(p)}" cy="{f(samples[p])}" r="4"/>')

    # CPU: ISR k highlighted, neighbours faint.
    for i, p in enumerate(P[:3]):
        cls = "isr" if i == 1 else "isrf"
        a(f'  <rect class="{cls}" x="{f(p + 4)}" y="272" width="72" height="18" rx="3"/>')
        if i == 1:
            a(f'  <text class="fg" x="{f(p + 40)}" y="285" text-anchor="middle" font-size="11">ISR k → d_k</text>')
    latch = V[1] if half else P[2]
    a(f'  <path class="arr" d="M{f(P[1] + 76)} 281 H{f(latch - 10)} L{f(latch - 2)} 297" marker-end="url(#a)"/>')
    if half:
        a(f'  <text class="dlt" x="{f(V[1] + 4)}" y="268" font-size="11">deadline</text>')

    # Applied duty windows.
    if half:
        wins = [(P[0], V[0], "", "dk1"), (V[0], V[1], "d_k−1", "dk1"), (V[1], V[2], "d_k", "dk"),
                (V[2], P[3], "", "dk1")]
    else:
        wins = [(P[0], P[1], "d_k−2", "dk1"), (P[1], P[2], "d_k−1", "dk1"), (P[2], P[3], "d_k", "dk")]
    for x0, x1, t, cls in wins:
        a(f'  <rect class="{cls}" x="{f(x0)}" y="302" width="{f(x1 - x0)}" height="20"/>')
        if t:
            a(f'  <text class="fg" x="{f((x0 + x1) / 2)}" y="316" text-anchor="middle" font-size="11">{t} applied</text>')

    # t_adv: from sample k to the centre of the window d_k acts in.
    c = (V[1] + V[2]) / 2 if half else (P[2] + P[3]) / 2
    lbl = "t_adv = 1.0·Ts" if half else "t_adv = 1.5·Ts"
    a(f'  <path class="arr" d="M{f(P[1])} 342 H{f(c)}" marker-start="url(#a)" marker-end="url(#a)"/>')
    a(f'  <line class="mk" x1="{f(c)}" y1="326" x2="{f(c)}" y2="348"/>')
    a(f'  <text class="fg" x="{f((P[1] + c) / 2)}" y="337" text-anchor="middle" font-size="11">{lbl}</text>')

    # Observer note.
    if half:
        note = "sample k+1 already sees d_k; the interval S k → S k+1 is ½ d_k−1 + ½ d_k"
    else:
        note = "sample k+1 still sees d_k−1; d_k shows first at sample k+2"
    a(f'  <text class="obst" x="{f(X0)}" y="368" font-size="11">{note}</text>')
    a(f'  <text class="mut" x="{f(X0)}" y="386" font-size="11">● sample: centre of the low-side window, '
      'where the rippled current equals its average.</text>')
    a(f'  <text class="mut" x="{f(X0)}" y="402" font-size="11">S/U: sample + update (preload → active CCR).'
      + ('  U: update only.' if half else '') + '  Current illustrative.</text>')
    a(f'  <text class="mut" x="{f(X0)}" y="418" font-size="11">Duties follow a sine and change a little every '
      'period; ISR k makes a step so the delay is visible.</text>')
    a('</svg>')
    return "\n".join(o) + "\n"


open(f"{OUT}/timing.svg", "w").write(build(False))
open(f"{OUT}/timing-half.svg", "w").write(build(True))
